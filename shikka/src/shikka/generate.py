#!/usr/bin/env python3
"""Resolve Cargo units into Buck rules without maintaining a second dependency graph.

Uses the initialized project toolchain and Cargo-vendored dependency sources.
Cargo's unit graph, rather than metadata's package-level feature union, owns
resolver 3 host/target features, build scripts, profiles and dependency renames.
"""
import argparse
import hashlib
from collections import deque
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tomllib

GENERATED = "# Generated by Shikka from Cargo unit graphs; do not edit.\n"
EXCLUDED = ["BUCK", "BUCK.v2", "PACKAGE", "BUILD", "BUILD.bazel", "TARGETS", ".buckconfig", ".buckrootconfig", "buckal.toml", "target/**", "buck-out/**", ".buckal/**", ".shikka/**", ".git/**"]
PROFILES = ["dev", "release", "test"]


def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"))


def digest(value):
    return hashlib.sha256(canonical(value).encode()).hexdigest()[:20]


def starlark(value):
    if value is None:
        return "None"
    if isinstance(value, bool):
        return "True" if value else "False"
    if isinstance(value, dict):
        return "{" + ", ".join(starlark(k) + ": " + starlark(v) for k, v in value.items()) + "}"
    if isinstance(value, list):
        return "[" + ", ".join(starlark(v) for v in value) + "]"
    return json.dumps(value)


def rule(rule_type, **attrs):
    return rule_type + "(\n" + "".join("    " + k + " = " + starlark(v) + ",\n" for k, v in attrs.items()) + ")\n\n"


def package_records(meta, root):
    records = {}
    for package in meta["packages"]:
        manifest = Path(package["manifest_path"])
        external = package["source"] is not None
        path = manifest.parent.relative_to(root).as_posix().removeprefix("./")
        path = "" if path == "." else path
        identity = package["id"] if external else "path:" + path + "#" + package["name"] + "@" + package["version"]
        data = {key: package.get(key) for key in ["name", "version", "description", "authors", "homepage", "repository", "license", "license_file", "readme", "rust_version", "links"]}
        data.update(id=identity, path=path, external=external, features=sorted(package["features"]), has_lib=any(any(k in ["lib", "rlib", "dylib", "proc-macro", "cdylib", "staticlib"] for k in t["kind"]) for t in package["targets"]))
        records[package["id"]] = data
    return records


def lto_modes(graph):
    """Adapted from Cargo 1.99.0's LTO planner; see CARGO-LICENSE-MIT.

    https://github.com/rust-lang/cargo/blob/5f94df4789f005f9a352888e8355ffc645b7ed0e/src/compiler/lto.rs
    """
    units = graph["units"]
    modes = {}
    pending = []
    can_lto = {"bin", "staticlib", "cdylib"}
    dynamic = {"dylib", "cdylib", "proc-macro"}

    def host(unit):
        return bool({"custom-build", "proc-macro"} & set(unit["target"]["kind"]))

    def needs_object(kinds):
        return bool((can_lto | dynamic) & set(kinds))

    def object_mode(kinds):
        return "object" if all(kind == "dylib" for kind in kinds) else "object-bitcode"

    for index in graph["roots"]:
        unit = units[index]
        requested = unit["profile"]["lto"]
        kinds = unit["target"]["crate_types"]
        if requested in (False, "false") or host(unit):
            mode = "object"
        elif requested == "off":
            mode = "off"
        else:
            mode = object_mode(kinds) if needs_object(kinds) else "bitcode"
        pending.append((index, mode))

    while pending:
        index, parent = pending.pop()
        unit = units[index]
        kinds = ["bin"] if unit["mode"] in {"test", "doctest"} else unit["target"]["crate_types"]
        requested = unit["profile"]["lto"]
        if host(unit):
            mode = "object"
        elif all(kind in can_lto for kind in kinds):
            mode = "object" if requested in (False, "false") else "off" if requested == "off" else "run:" + ("fat" if requested is True else requested)
        elif parent.startswith("run:"):
            mode = object_mode(kinds) if needs_object(kinds) else "bitcode"
        elif parent == "bitcode" and needs_object(kinds):
            mode = object_mode(kinds)
        else:
            mode = parent
        previous = modes.get(index)
        if previous is not None and previous != mode:
            if previous.startswith("run:") or mode.startswith("run:"):
                mode = mode if mode.startswith("run:") else previous
            elif "off" in (previous, mode):
                mode = "off"
            else:
                mode = "object-bitcode"
        if previous == mode:
            continue
        modes[index] = mode
        pending.extend((dep["index"], mode) for dep in unit["dependencies"])
    return modes


def scheduling_priorities(graph):
    """Longest remaining dependency path to any root in Cargo's complete graph.

    A root has rank zero unless another root depends on it. Walking consumer
    edges in reverse gives dependencies larger ranks, independent of names or
    source paths. Ranks are scheduling hints, not part of unit/source identity
    or the serialized compiler action; selecting fewer roots keeps static ranks.
    """
    units = graph["units"]
    count = len(units)
    consumers = [0] * count
    dependencies = []

    def checked_index(index):
        if type(index) is not int or not 0 <= index < count:
            raise ValueError("Cargo unit graph index out of range")
        return index

    for unit in units:
        edges = [checked_index(dep["index"]) for dep in unit["dependencies"]]
        dependencies.append(edges)
        for dependency in edges:
            consumers[dependency] += 1
    priorities = [-1] * count
    for root in graph["roots"]:
        priorities[checked_index(root)] = 0
    pending = deque(index for index, degree in enumerate(consumers) if degree == 0)
    visited = 0
    while pending:
        index = pending.popleft()
        visited += 1
        for dependency in dependencies[index]:
            if priorities[index] >= 0:
                priorities[dependency] = max(priorities[dependency], priorities[index] + 1)
            consumers[dependency] -= 1
            if consumers[dependency] == 0:
                pending.append(dependency)
    if visited != count:
        raise ValueError("Cargo unit graph unexpectedly cyclic")
    if any(priority < 0 for priority in priorities):
        raise ValueError("Cargo unit graph contains units unreachable from its roots")
    return priorities


def units_from_graph(graph, packages, meta, dylib_extension=".so"):
    raw = graph["units"]
    prepared = []
    metadata = {p["id"]: p for p in meta["packages"]}
    modes = lto_modes(graph)
    for index, unit in enumerate(raw):
        package = packages[unit["pkg_id"]]
        target = dict(unit["target"])
        target["src_path"] = Path(target["src_path"]).relative_to(Path(metadata[unit["pkg_id"]]["manifest_path"]).parent).as_posix()
        prepared.append({"package": package, "target": target, "profile": unit["profile"], "platform": unit["platform"], "mode": unit["mode"], "features": unit["features"], "dependencies": [{k: v for k, v in dep.items() if k != "index"} for dep in unit["dependencies"]]})
        prepared[-1]["lto_mode"] = modes[index]
        if unit["mode"] == "test":
            # Cargo tests may embed paths, change cwd, and launch child processes.
            prepared[-1]["test_root"] = meta["workspace_root"]
    keys = {}
    visiting = set()
    def key(index):
        if index in keys:
            return keys[index]
        if index in visiting:
            raise ValueError("Cargo unit graph unexpectedly cyclic")
        visiting.add(index)
        spec = prepared[index]
        identity = {k: v for k, v in spec.items() if k not in {"package", "dependencies"}}
        identity["package"] = spec["package"]["id"]
        identity["dependencies"] = sorted([(key(dep["index"]), {k: v for k, v in dep.items() if k != "index"}) for dep in raw[index]["dependencies"]], key=canonical)
        keys[index] = digest(identity)
        visiting.remove(index)
        return keys[index]
    for index, spec in enumerate(prepared):
        spec["key"] = key(index)
        name = spec["target"]["name"].replace("-", "_")
        kinds = spec["target"]["crate_types"]
        if spec["mode"] == "run-custom-build":
            filename = ""
        elif spec["mode"] == "test" or "bin" in kinds:
            filename = name + "-" + spec["key"]
        elif any(kind in kinds for kind in ["dylib", "proc-macro", "cdylib"]):
            filename = "lib" + name + "-" + spec["key"] + dylib_extension
        elif "staticlib" in kinds:
            filename = "lib" + name + "-" + spec["key"] + ".a"
        else:
            filename = "lib" + name + "-" + spec["key"] + ".rlib"
        spec["filename"] = filename
    return prepared, keys


def outside_data(root, package_path):
    """Use the same literal-include contract as the existing Bazel generator."""
    base = root / package_path
    found = set()
    patterns = [
        (re.compile(r'include_(?:str|bytes)!\s*\(\s*"([^"]+)"'), False, False),
        (re.compile(r'include_(?:str|bytes)!\s*\(\s*concat!\(\s*"([^"]+)"'), False, True),
        (re.compile(r'env!\(\s*"CARGO_MANIFEST_DIR"\s*\)\s*\)?\s*\.join\(\s*(?:format!\(\s*)?"([^"]+)"'), True, False),
    ]
    for source in base.rglob("*.rs"):
        if any(part in {"target", "buck-out", ".git", ".shikka"} for part in source.relative_to(base).parts):
            continue
        text = source.read_text(errors="replace")
        for pattern, from_manifest, prefix in patterns:
            for match in pattern.finditer(text):
                value = match.group(1)
                if prefix:
                    value = value.rsplit("/", 1)[0] if "/" in value else "."
                value = re.sub(r"\{[^}]*\}", "*", value)
                parent = base if from_manifest else source.parent
                candidate = Path(os.path.normpath(parent / value))
                if not candidate.is_relative_to(root):
                    continue
                for path in root.glob(candidate.relative_to(root).as_posix()):
                    if path.is_relative_to(base) or base.is_relative_to(path):
                        continue
                    found.update(p for p in (path.rglob("*") if path.is_dir() else [path]) if p.is_file() and p.name not in EXCLUDED)
    return sorted(p.relative_to(root).as_posix() for p in found)



def generate(root, config, tools):
    from .project import app_inputs, cargo_configs, cargo, owned_write, read, tool_identity, write_json
    features =(["--features", config["features"]] if config["features"] else [])
    if config["no_default_features"]:
        features += ["--no-default-features"]
    common = ["--locked", "--offline", "--manifest-path", config["manifest"]]
    meta = json.loads(cargo(root, tools, ["metadata", "--format-version", "1", *common, *features]))
    packages = package_records(meta, root)
    files = {}
    sources = {}
    package_text = {}
    owners = sorted({p["path"] for p in packages.values()}, key=len, reverse=True)
    exports = {}
    for pkgid, package in sorted(packages.items()):
        path = package["path"]
        if path in package_text:
            sources[pkgid] = "//" + path + ":cargo-source"
            continue
        additions = {}
        if not package["external"]:
            for data_path in outside_data(root, path):
                owner = next((p for p in owners if p and data_path.startswith(p + "/")), "")
                relative = data_path[len(owner) + 1:] if owner else data_path
                name = "cargo-data-" + digest(relative)
                exports.setdefault(owner, {})[name] = relative
                additions[data_path] = "//" + owner + ":" + name
        prefix = path + "/" if path else ""
        package_text[path] = GENERATED + 'load("@shikka//:units.bzl", "cargo_source")\n\n'
        package_text[path] += ('cargo_source(\n    name = "cargo-source",\n    prefix = ' + starlark(path)
            + ',\n    files = {' + starlark(prefix) + ' + p: p for p in glob(["**/*"], exclude = '
            + starlark(EXCLUDED) + ')} | ' + starlark(additions) + ',\n    visibility = ["PUBLIC"],\n)\n\n')
        sources[pkgid] = "//" + path + ":cargo-source"
    targets = {}
    units_by_profile = {}
    for profile in config["profiles"]:
        command = ["test" if profile == "test" else "build", *common, "--workspace", "--unit-graph", "-Z", "unstable-options", *features]
        command += ["--lib", "--bins", "--tests"] if profile == "test" else ["--profile", profile]
        graph = json.loads(cargo(root, tools, command))
        priorities = scheduling_priorities(graph)
        units, keys = units_from_graph(graph, packages, meta, tools["dylib_extension"])
        graph_path = ".shikka/graph/" + profile
        text = GENERATED + 'load("@shikka//:units.bzl", "cargo_unit")\n\n'
        records = []
        for index, spec in sorted(enumerate(units), key=lambda item: item[1]["key"]):
            deps = [":" + keys[dep["index"]] for dep in graph["units"][index]["dependencies"]]
            text += rule("cargo_unit", name=spec["key"], spec=canonical(spec), source=sources[graph["units"][index]["pkg_id"]], deps=deps, priority=priorities[index], visibility=["PUBLIC"])
            records.append({"label": "//" + graph_path + ":" + spec["key"], "package": spec["package"]["name"], "target": spec["target"]["name"], "kind": spec["target"]["kind"], "mode": spec["mode"], "filename": spec["filename"], "external": spec["package"]["external"]})
        files[graph_path + "/BUCK"] = text
        units_by_profile[profile] = records
        roots = {keys[index] for index in graph["roots"]}
        targets[profile] = [r for r in records if r["label"].rsplit(":", 1)[1] in roots and not r["external"]]
    for path, text in package_text.items():
        files[(path + "/" if path else "") + "BUCK"] = text
    for owner, extra in exports.items():
        path = (owner + "/" if owner else "") + "BUCK"
        files.setdefault(path, GENERATED)
        for name, src in sorted(extra.items()):
            files[path] += rule("export_file", name=name, src=src, visibility=["PUBLIC"])
    files[".shikka/BUCK"] = GENERATED + 'export_file(name="toolchain.json", visibility=["PUBLIC"])\n'
    previous_path = root / ".shikka/graph.json"
    previous = read(previous_path) if previous_path.exists() else {}
    # Validate ownership for the entire update before writing its first file.
    for path in files:
        dest = root / path
        if dest.exists() and not dest.read_text().startswith(GENERATED.splitlines()[0]):
            raise ValueError("Refusing to replace project file: " + str(dest))
    for path, content in files.items():
        owned_write(root, path, content)
    for path, expected in previous.get("generated", {}).items():
        dest = root / path
        if path not in files and dest.is_file() and hashlib.sha256(dest.read_bytes()).hexdigest() == expected:
            dest.unlink()
    inputs = {Path(meta["workspace_root"]) / "Cargo.lock", root / config["manifest"], root / ".shikka/vendor.toml", root / ".shikka/project.json", root / ".shikka/toolchain.json"}
    for package in meta["packages"]:
        manifest = Path(package["manifest_path"])
        inputs.add(manifest)
        for parent in manifest.parent.parents:
            if not parent.is_relative_to(root):
                break
            if (parent / "Cargo.toml").is_file():
                inputs.add(parent / "Cargo.toml")
    for path in [root / ".cargo/config", root / ".cargo/config.toml", root / "rust-toolchain", root / "rust-toolchain.toml"]:
        if path.is_file(): inputs.add(path)
    state = {"schema": 1, "cargo_configs": cargo_configs(root), "targets": targets, "units": units_by_profile, "app_inputs": app_inputs(),
             "toolchain": tool_identity(tools),
             "inputs": {p.relative_to(root).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(inputs)},
             "generated": {p: hashlib.sha256(content.encode()).hexdigest() for p, content in files.items()}}
    write_json(previous_path, state)
    return state


def current(root):
    from .project import app_inputs, cargo_configs, file_identity, read
    path = root / ".shikka/graph.json"
    if not path.exists():
        raise ValueError("No graph; run shikka generate.")
    state = read(path)
    stale = [name for name, expected in state["inputs"].items()
             if not (root / name).is_file() or hashlib.sha256((root / name).read_bytes()).hexdigest() != expected]
    if state.get("cargo_configs") != cargo_configs(root): stale.append("Cargo configuration files")
    if state["app_inputs"] != app_inputs(): stale.append("Shikka action/generator version")
    # A compiler replaced at its recorded path would otherwise keep the action
    # identities, and so the cached outputs, of the one it replaced.
    replaced = sorted(name for name, recorded in state.get("toolchain", {}).items() if file_identity(recorded["tool"]) != recorded)
    if replaced: stale.append("Toolchain files replaced on disk: " + ", ".join(replaced))
    if stale:
        raise ValueError("Build inputs changed; run shikka generate:\n" + "\n".join(stale))
    return state
