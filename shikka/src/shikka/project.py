"""Project-local configuration and explicit, fingerprinted native toolchains."""
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import tomllib

RESOURCES = Path(__file__).parent / "resources"
MARKER = "# Generated by Shikka"


def read(path):
    return json.loads(Path(path).read_text())


def atomic_write(path, text, mode=0o600):
    path = Path(path)
    if path.is_file() and path.read_text() == text and (path.stat().st_mode & 0o777) == mode:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(dir=path.parent)
    try:
        with os.fdopen(fd, "w") as stream:
            stream.write(text)
            stream.flush()
            os.fsync(stream.fileno())
        os.chmod(temporary, mode)
        os.replace(temporary, path)
    finally:
        Path(temporary).unlink(missing_ok=True)


def write_json(path, data):
    atomic_write(path, json.dumps(data, sort_keys=True, indent=2) + "\n")


def fingerprint(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True).encode()).hexdigest()


def executable(value, default):
    name = value or default
    path = shutil.which(name)
    if path is None:
        raise ValueError(f"Missing executable {name!r}; provide its absolute path.")
    # Preserve executable names: resolving rustup or compiler-wrapper symlinks
    # changes dispatch semantics.
    return os.path.abspath(path)


def output(command):
    return subprocess.check_output(command, text=True).strip()


TOOLS = [("rustc", "rustc"), ("cargo", "cargo"), ("cc", "cc"), ("cxx", "c++"), ("ar", "ar")]


def packaged_toolchain():
    return read(os.environ["SHIKKA_TOOLCHAIN"]) if os.environ.get("SHIKKA_TOOLCHAIN") else {}


def requested_tools(args):
    """The tool choices `init` records in project.json, and the PATH actions use.

    A choice is an absolute path, so a later `generate` resolves the same file
    whatever shell it runs in. It names the file the user would run (a rustup
    proxy stays a proxy), not what that dispatches to today. None defers to the
    packaged toolchain, which a newer package may replace.
    """
    defaults = packaged_toolchain()
    tools = {}
    for key, default in TOOLS:
        chosen = getattr(args, key, None)
        tools[key] = executable(chosen, default) if chosen or not defaults.get(key) else None
    return tools, None if defaults.get("BUILD_PATH") else os.environ.get("PATH", "")


def workspace_directory(root, config):
    """The Cargo workspace: the project root, or a directory `init --root` put below it.

    Cargo and rustup read their configuration from the directory they run in
    and its parents, so Cargo runs here, as it does for the project's developers.
    """
    return root / config.get("workspace", "")


def toolchain(config, root, recorded=None):
    """Resolve and probe the project's recorded tool choices.

    Both `init` and `generate` run this. Compiler paths can outlive the
    compiler they named (rustup and system packages update in place), so the
    probed versions, and with them every action's identity, are only as fresh
    as the last run. `tool_identity` lets builds notice when that is stale.
    """
    defaults = packaged_toolchain()
    requested = config.get("tools") or {}
    tools = dict(defaults)
    for key, default in TOOLS:
        tools[key] = executable(requested.get(key) or defaults.get(key), default)
    # Resolve rustup's dispatchers while the caller's project/toolchain context
    # is available. Compiler actions deliberately have a private HOME.
    sysroot = Path(subprocess.check_output([tools["rustc"], "--print", "sysroot"], cwd=workspace_directory(root, config), text=True).strip())
    for key in ["rustc", "cargo"]:
        if Path(tools[key]).resolve().name == "rustup":
            tools[key] = str(sysroot / "bin" / key)
    for key in ["cc", "cxx", "ar"]:
        resolved = Path(tools[key]).resolve()
        if resolved.is_relative_to("/nix/store"):
            tools[key] = str(resolved)
    tools["python"] = executable(sys.executable, "python3")
    version = output([tools["rustc"], "-vV"])
    tools["target"] = next(line.split(": ", 1)[1] for line in version.splitlines() if line.startswith("host: "))
    tools["rustlib"] = output([tools["rustc"], "--print", "target-libdir"])
    # The PATH recorded at init stays the actions' PATH: the shell that happens
    # to run `generate` must not change every action's identity.
    tools["BUILD_PATH"] = defaults.get("BUILD_PATH") or config.get("build_path") or (recorded or {}).get("BUILD_PATH") or os.environ.get("PATH", "")
    tools["versions"] = {"rustc": version, "cargo": output([tools["cargo"], "-V"]), "cc": output([tools["cc"], "--version"])}
    if sys.platform == "darwin":
        tools["SDKROOT"] = output(["xcrun", "--sdk", "macosx", "--show-sdk-path"])
        tools["sdk_version"] = output(["xcrun", "--sdk", "macosx", "--show-sdk-version"])
        # Darwin has no /proc/self/cwd. Crates can embed CARGO_MANIFEST_DIR;
        # scope action identity to the root until that runtime contract can be
        # relocated safely. Linux retains cross-worktree action identities.
        tools["execution_root"] = str(root)
        tools["dylib_extension"] = ".dylib"
    elif sys.platform == "linux":
        tools["dylib_extension"] = ".so"
    else:
        raise ValueError("Shikka currently supports Linux and macOS.")
    return tools


def file_identity(tool):
    """What `tool` names now: its resolved file, size and modification time."""
    path = os.path.realpath(tool)
    try:
        status = os.stat(path)
    except OSError:
        return {"tool": tool, "path": path}
    return {"tool": tool, "path": path, "size": status.st_size, "mtime_ns": status.st_mtime_ns}


def tool_identity(tools):
    """File identities of the probed tools, for noticing an in-place update.

    Stored with the graph state, not in toolchain.json: modification times are
    facts about this host and must not enter an action's identity.
    """
    paths = {key: tools[key] for key, _ in TOOLS}
    if sys.platform == "darwin":
        # /usr/bin/cc is a fixed shim. An Xcode or Command Line Tools update
        # replaces the compiler and SDK it dispatches to.
        paths["developer cc"] = output(["xcrun", "--find", "cc"])
        paths["sdk"] = os.path.join(tools["SDKROOT"], "SDKSettings.json")
    return {name: file_identity(path) for name, path in paths.items()}


def find_root():
    for path in [Path.cwd(), *Path.cwd().parents]:
        if (path / ".shikka/project.json").is_file():
            return path.resolve()
    raise ValueError("No Shikka project here; run shikka init --manifest-path PATH/Cargo.toml.")


def cargo(root, config, tools, arguments, *, vendored=True, capture=True):
    env = dict(os.environ, RUSTC=tools["rustc"], RUSTC_BOOTSTRAP="1", CARGO_TARGET_DIR=str(root / ".shikka/cargo-target"))
    for name in ["RUSTC_WRAPPER", "RUSTC_WORKSPACE_WRAPPER", "RUSTFLAGS", "CARGO_ENCODED_RUSTFLAGS"]:
        env.pop(name, None)
    command = [tools["cargo"]]
    if vendored:
        command += ["--config", str(root / ".shikka/vendor.toml")]
    return subprocess.run(command + arguments, cwd=workspace_directory(root, config), env=env, check=True, text=True,
                          stdout=subprocess.PIPE if capture else None).stdout


def owned_write(root, relative, content):
    path = root / relative
    if path.exists() and not path.read_text().startswith(MARKER):
        raise ValueError(f"Refusing to replace an existing project file: {path}")
    if not path.exists() or path.read_text() != content:
        atomic_write(path, content, 0o644)


def app_inputs():
    files = [Path(__file__).parent / "generate.py", *RESOURCES.iterdir()]
    return {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in files if p.is_file()}


def cargo_configs(directory):
    """The configuration files Cargo reads when it runs in `directory`."""
    paths = {parent / ".cargo" / name for parent in [directory, *directory.parents] for name in ["config", "config.toml"]}
    home = Path(os.environ.get("CARGO_HOME", Path.home() / ".cargo"))
    paths.update(home / name for name in ["config", "config.toml"])
    return {str(path): hashlib.sha256(path.read_bytes()).hexdigest() for path in sorted(paths) if path.is_file()}


def validate_cargo_config(directory, tools):
    for name in os.environ:
        if name in {"RUSTFLAGS", "CARGO_ENCODED_RUSTFLAGS", "RUSTC_WRAPPER", "RUSTC_WORKSPACE_WRAPPER", "CARGO_BUILD_TARGET", "CARGO_BUILD_RUSTC", "CARGO_BUILD_RUSTFLAGS", "CARGO_BUILD_RUSTC_WRAPPER", "CARGO_BUILD_RUSTC_WORKSPACE_WRAPPER"} or (name.startswith("CARGO_TARGET_") and name.endswith(("_RUSTFLAGS", "_LINKER", "_RUNNER"))):
            if os.environ[name]:
                raise ValueError("Unsupported implicit Cargo setting: " + name)
    for name in cargo_configs(directory):
        data = tomllib.loads(Path(name).read_text())
        unsupported = set(data.get("build", {})) & {"target", "rustflags", "rustc", "rustc-wrapper", "rustc-workspace-wrapper", "rustdocflags"}
        if unsupported or data.get("env") or data.get("unstable"):
            raise ValueError("Unsupported Cargo build/env/unstable settings in " + name)
        for target, settings in data.get("target", {}).items():
            if target == tools["target"] or target.startswith("cfg("):
                if settings:
                    raise ValueError("Unsupported native or cfg-target Cargo settings in " + name)
